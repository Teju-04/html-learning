let value = 1;

// while syntax, example

while (value <= 5) {
    console.log('Number is ',value);
    value ++;
}

// do while syntax, example

let value2 = 6;

do {
    console.log('Number is ',value2);
    value2 ++;
} while(value2 <= 5);
// It iterates atlease once

